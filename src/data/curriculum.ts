// Helper function to get curriculum by grade
export const getCurriculumByGrade = (grade: 6 | 7 | 8 | 9): GradeCurriculum | undefined => {
    return curriculum.find(c => c.grade === grade);
};

// Helper function to get topic by ID and grade
export const getTopicById = (grade: number, topicId: string) => {
    const gradeCurriculum = curriculum.find(c => c.grade === grade);
    return gradeCurriculum?.topics.find(t => t.id === topicId);
};

// Helper function to get lesson by ID
export const getLessonById = (grade: number, lessonId: number) => {
    const gradeCurriculum = curriculum.find(c => c.grade === grade);
    if (!gradeCurriculum) return null;

    for (const topic of gradeCurriculum.topics) {
        const lesson = topic.lessons.find(l => l.id === lessonId);
        if (lesson) {
            return {
                lesson,
                topic
            };
        }
    }
    return null;
};
